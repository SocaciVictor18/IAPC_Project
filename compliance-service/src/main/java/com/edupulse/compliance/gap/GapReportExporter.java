package com.edupulse.compliance.gap;

import com.edupulse.compliance.gap.GapModels.Evidence;
import com.edupulse.compliance.gap.GapModels.Finding;
import org.apache.poi.xwpf.usermodel.ParagraphAlignment;
import org.apache.poi.xwpf.usermodel.XWPFDocument;
import org.apache.poi.xwpf.usermodel.XWPFParagraph;
import org.apache.poi.xwpf.usermodel.XWPFRun;
import org.apache.poi.xwpf.usermodel.XWPFTable;
import org.apache.poi.xwpf.usermodel.XWPFTableRow;
import org.openpdf.text.Chunk;
import org.openpdf.text.Document;
import org.openpdf.text.Element;
import org.openpdf.text.Font;
import org.openpdf.text.FontFactory;
import org.openpdf.text.PageSize;
import org.openpdf.text.Paragraph;
import org.openpdf.text.Phrase;
import org.openpdf.text.pdf.PdfPCell;
import org.openpdf.text.pdf.PdfPTable;
import org.openpdf.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;
import tools.jackson.databind.SerializationFeature;
import tools.jackson.databind.json.JsonMapper;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/** Exportable evaluation (FR "Automated Gap Analysis Reports"): PDF, DOCX, CSV and JSON. */
@Component
public class GapReportExporter {

    static final String DISCLAIMER = "AI-assisted analysis generated by EduPulse AI. Findings must be reviewed and "
            + "confirmed by a qualified compliance professional before being relied upon.";

    private final JsonMapper json = JsonMapper.builder().enable(SerializationFeature.INDENT_OUTPUT).build();

    public byte[] json(Map<String, Object> report, List<Finding> findings) {
        Map<String, Object> out = new LinkedHashMap<>(report);
        out.put("findings", findings);
        out.put("disclaimer", DISCLAIMER);
        return json.writeValueAsBytes(out);
    }

    public byte[] csv(List<Finding> findings) {
        StringBuilder sb = new StringBuilder("ordinal,requirement_ref,requirement_page,obligation,status,severity,requirement,rationale,recommendation,evidence\n");
        for (Finding f : findings) {
            sb.append(String.join(",", String.valueOf(f.ordinal()), c(f.requirementRef()), c(f.requirementPage()),
                    c(f.obligationType()), c(f.status()), c(f.severity()), c(f.requirementText()), c(f.rationale()),
                    c(f.recommendation()), c(evidenceLine(f.evidence())))).append('\n');
        }
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    public byte[] pdf(Map<String, Object> report, List<Finding> findings) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4.rotate(), 36, 36, 36, 36);
        PdfWriter.getInstance(doc, out);
        doc.open();
        Font title = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18);
        Font h2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12);
        Font normal = FontFactory.getFont(FontFactory.HELVETICA, 9);
        Font bold = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9);
        Font small = FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 8, Color.DARK_GRAY);

        doc.add(new Paragraph("Compliance Gap Analysis Report", title));
        doc.add(new Paragraph("Regulation: " + v(report.get("regulation_title")), h2));
        doc.add(new Paragraph("Requested by: " + v(report.get("requested_by_email")) + "    Created: " + v(report.get("created_at"))
                + "    Completed: " + v(report.get("finished_at")), normal));
        doc.add(new Paragraph("Report id: " + v(report.get("id")), normal));
        doc.add(Chunk.NEWLINE);

        PdfPTable summary = new PdfPTable(5);
        summary.setWidthPercentage(60);
        summary.setHorizontalAlignment(Element.ALIGN_LEFT);
        for (String h : List.of("Requirements", "Covered", "Partial", "Gaps", "N/A")) {
            summary.addCell(header(h, bold));
        }
        for (String k : List.of("total_requirements", "covered", "partial", "gaps", "not_applicable")) {
            summary.addCell(new Phrase(v(report.get(k)), normal));
        }
        doc.add(summary);
        doc.add(Chunk.NEWLINE);
        doc.add(new Paragraph("Executive summary", h2));
        doc.add(new Paragraph(v(report.get("summary")), normal));
        doc.add(Chunk.NEWLINE);

        doc.add(new Paragraph("Findings", h2));
        PdfPTable table = new PdfPTable(new float[]{3, 22, 5, 8, 7, 25, 30});
        table.setWidthPercentage(100);
        table.setHeaderRows(1);
        for (String h : List.of("#", "Requirement", "Page", "Status", "Severity", "Rationale / recommendation", "Evidence (document, page, snippet)")) {
            table.addCell(header(h, bold));
        }
        for (Finding f : findings) {
            table.addCell(new Phrase(String.valueOf(f.ordinal()), normal));
            table.addCell(new Phrase(pdfSafe((f.requirementRef() == null || f.requirementRef().isBlank() ? "" : f.requirementRef() + ": ")
                    + f.requirementText()), normal));
            table.addCell(new Phrase(v(f.requirementPage()), normal));
            PdfPCell status = new PdfPCell(new Phrase(f.status(), bold));
            status.setBackgroundColor(color(f.status()));
            table.addCell(status);
            table.addCell(new Phrase(v(f.severity()), normal));
            table.addCell(new Phrase(v(f.rationale()) + (f.recommendation() == null || f.recommendation().isBlank()
                    ? "" : "\n> " + pdfSafe(f.recommendation())), normal));
            table.addCell(new Phrase(evidenceBlock(f.evidence()), normal));
        }
        doc.add(table);
        doc.add(Chunk.NEWLINE);
        doc.add(new Paragraph(DISCLAIMER, small));
        doc.close();
        return out.toByteArray();
    }

    public byte[] docx(Map<String, Object> report, List<Finding> findings) throws IOException {
        try (XWPFDocument doc = new XWPFDocument(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            XWPFParagraph t = doc.createParagraph();
            t.setAlignment(ParagraphAlignment.LEFT);
            XWPFRun tr = t.createRun();
            tr.setBold(true);
            tr.setFontSize(18);
            tr.setText("Compliance Gap Analysis Report");
            para(doc, "Regulation: " + v(report.get("regulation_title")), true);
            para(doc, "Requested by: " + v(report.get("requested_by_email")) + " | Created: " + v(report.get("created_at"))
                    + " | Completed: " + v(report.get("finished_at")), false);
            para(doc, "Totals – requirements: " + v(report.get("total_requirements")) + ", covered: " + v(report.get("covered"))
                    + ", partial: " + v(report.get("partial")) + ", gaps: " + v(report.get("gaps"))
                    + ", not applicable: " + v(report.get("not_applicable")), false);
            para(doc, "Executive summary", true);
            para(doc, v(report.get("summary")), false);
            para(doc, "Findings", true);

            XWPFTable table = doc.createTable(1, 6);
            List<String> headers = List.of("#", "Requirement", "Page", "Status / severity", "Rationale / recommendation", "Evidence");
            XWPFTableRow head = table.getRow(0);
            for (int i = 0; i < headers.size(); i++) {
                head.getCell(i).setText(headers.get(i));
            }
            for (Finding f : findings) {
                XWPFTableRow row = table.createRow();
                row.getCell(0).setText(String.valueOf(f.ordinal()));
                row.getCell(1).setText((f.requirementRef() == null || f.requirementRef().isBlank() ? "" : f.requirementRef() + ": ") + f.requirementText());
                row.getCell(2).setText(v(f.requirementPage()));
                row.getCell(3).setText(f.status() + (f.severity() == null ? "" : " / " + f.severity()));
                row.getCell(4).setText(v(f.rationale()) + (f.recommendation() == null || f.recommendation().isBlank() ? "" : " → " + f.recommendation()));
                row.getCell(5).setText(evidenceLine(f.evidence()));
            }
            XWPFParagraph d = doc.createParagraph();
            XWPFRun dr = d.createRun();
            dr.setItalic(true);
            dr.setFontSize(8);
            dr.setText(DISCLAIMER);
            doc.write(out);
            return out.toByteArray();
        }
    }

    private static void para(XWPFDocument doc, String text, boolean bold) {
        XWPFRun r = doc.createParagraph().createRun();
        r.setBold(bold);
        r.setText(text);
    }

    private static PdfPCell header(String text, Font font) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setBackgroundColor(new Color(230, 230, 240));
        return cell;
    }

    private static Color color(String status) {
        return switch (status) {
            case "COVERED" -> new Color(198, 239, 206);
            case "PARTIAL" -> new Color(255, 235, 156);
            case "GAP" -> new Color(255, 199, 206);
            default -> new Color(230, 230, 230);
        };
    }

    private static String evidenceBlock(List<Evidence> evidence) {
        if (evidence == null || evidence.isEmpty()) {
            return "-";
        }
        return evidence.stream().map(e -> e.source() + (e.page() != null ? ", p. " + e.page() : e.section() != null ? ", " + e.section() : "")
                + ": \"" + truncate(e.snippet(), 220) + "\"").collect(Collectors.joining("\n"));
    }

    private static String evidenceLine(List<Evidence> evidence) {
        return evidence == null ? "" : evidence.stream()
                .map(e -> e.source() + (e.page() != null ? " p." + e.page() : "") + " – " + truncate(e.snippet(), 160))
                .collect(Collectors.joining(" | "));
    }

    private static String truncate(String s, int n) {
        String t = pdfSafe(s);
        return t.length() <= n ? t : t.substring(0, n) + "...";
    }

    private static String v(Object o) {
        return o == null ? "-" : pdfSafe(String.valueOf(o));
    }

    /** The standard PDF fonts (WinAnsi) lack some glyphs; map them to plain ASCII. */
    static String pdfSafe(String s) {
        if (s == null) {
            return "";
        }
        return s.replace('•', '-').replace('�', '-').replace("…", "...")
                .replace('–', '-').replace('—', '-').replace('→', '>');
    }

    private static String c(Object o) {
        if (o == null) {
            return "";
        }
        String s = String.valueOf(o).replace("\"", "\"\"");
        return "\"" + s + "\"";
    }
}
