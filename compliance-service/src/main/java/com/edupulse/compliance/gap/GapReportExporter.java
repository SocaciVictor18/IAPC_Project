package com.edupulse.compliance.gap;

import com.edupulse.compliance.gap.GapModels.Evidence;
import com.edupulse.compliance.gap.GapModels.Finding;
import org.openpdf.text.Document;
import org.openpdf.text.Font;
import org.openpdf.text.FontFactory;
import org.openpdf.text.PageSize;
import org.openpdf.text.Paragraph;
import org.openpdf.text.Phrase;
import org.openpdf.text.pdf.PdfPCell;
import org.openpdf.text.pdf.PdfPTable;
import org.openpdf.text.pdf.PdfWriter;
import org.springframework.stereotype.Component;
import tools.jackson.databind.SerializationFeature;
import tools.jackson.databind.json.JsonMapper;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/** Exportable evaluation (FR "Automated Gap Analysis Reports"): PDF and JSON. */
@Component
public class GapReportExporter {

    static final String DISCLAIMER = "AI-assisted analysis generated by EduPulse AI - to be reviewed by the compliance team.";

    private final JsonMapper json = JsonMapper.builder().enable(SerializationFeature.INDENT_OUTPUT).build();

    public byte[] json(Map<String, Object> report, List<Finding> findings) {
        Map<String, Object> out = new LinkedHashMap<>(report);
        out.put("findings", findings);
        return json.writeValueAsBytes(out);
    }

    public byte[] pdf(Map<String, Object> report, List<Finding> findings) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4.rotate(), 36, 36, 36, 36);
        PdfWriter.getInstance(doc, out);
        doc.open();
        Font title = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18);
        Font h2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12);
        Font normal = FontFactory.getFont(FontFactory.HELVETICA, 9);
        Font bold = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9);

        doc.add(new Paragraph("Compliance Gap Analysis Report", title));
        doc.add(new Paragraph("Regulation: " + v(report.get("regulation_title")), h2));
        doc.add(new Paragraph("Requested by " + v(report.get("requested_by_email")) + " on " + v(report.get("created_at")), normal));
        doc.add(new Paragraph("Requirements: " + v(report.get("total_requirements")) + "   Covered: " + v(report.get("covered"))
                + "   Partial: " + v(report.get("partial")) + "   Gaps: " + v(report.get("gaps")), bold));
        doc.add(new Paragraph(" "));
        doc.add(new Paragraph("Executive summary", h2));
        doc.add(new Paragraph(v(report.get("summary")), normal));
        doc.add(new Paragraph(" "));

        PdfPTable table = new PdfPTable(new float[]{3, 25, 5, 8, 27, 32});
        table.setWidthPercentage(100);
        table.setHeaderRows(1);
        for (String h : List.of("#", "Requirement", "Page", "Status", "Rationale / recommendation", "Evidence (document, page, snippet)")) {
            PdfPCell cell = new PdfPCell(new Phrase(h, bold));
            cell.setBackgroundColor(new Color(230, 230, 240));
            table.addCell(cell);
        }
        for (Finding f : findings) {
            table.addCell(new Phrase(String.valueOf(f.ordinal()), normal));
            table.addCell(new Phrase(v((f.requirementRef() == null || f.requirementRef().isBlank() ? "" : f.requirementRef() + ": ")
                    + f.requirementText()), normal));
            table.addCell(new Phrase(v(f.requirementPage()), normal));
            PdfPCell status = new PdfPCell(new Phrase(f.status() + (f.severity() == null ? "" : "\n" + f.severity()), bold));
            status.setBackgroundColor(switch (f.status()) {
                case "COVERED" -> new Color(198, 239, 206);
                case "PARTIAL" -> new Color(255, 235, 156);
                default -> new Color(255, 199, 206);
            });
            table.addCell(status);
            table.addCell(new Phrase(v(f.rationale()) + (f.recommendation() == null || f.recommendation().isBlank()
                    ? "" : "\n> " + v(f.recommendation())), normal));
            table.addCell(new Phrase(evidence(f.evidence()), normal));
        }
        doc.add(table);
        doc.add(new Paragraph(" "));
        doc.add(new Paragraph(DISCLAIMER, normal));
        doc.close();
        return out.toByteArray();
    }

    private static String evidence(List<Evidence> evidence) {
        if (evidence == null || evidence.isEmpty()) {
            return "-";
        }
        return evidence.stream()
                .map(e -> e.source() + (e.page() != null ? ", p. " + e.page() : "") + ": \"" + shorten(e.snippet()) + "\"")
                .collect(Collectors.joining("\n"));
    }

    private static String shorten(String s) {
        String t = v(s);
        return t.length() <= 200 ? t : t.substring(0, 200) + "...";
    }

    /** The built-in PDF fonts miss some characters (bullets, arrows): replace them. */
    private static String v(Object o) {
        if (o == null) {
            return "-";
        }
        return String.valueOf(o).replace('•', '-').replace('�', '-').replace("…", "...")
                .replace('–', '-').replace('—', '-');
    }
}
